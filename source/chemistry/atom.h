        constexpr std::optional<Radius> neutral_radius() const
        {
            if (element == Element::none)
                return std::nullopt;
            if (is_metal(element))
                return metallic_radius();
            return van_der_waals_radius();
        }

        static constexpr Radius defaultDisplayRadius{ 100_pm };

        constexpr Radius display_radius() const
        {
            if (element == Element::none)
                return Radius{};

            if (charge != 0)
                if (auto radius{ ionic_radius() })
                    return *radius;

            if (auto radius{ neutral_radius() })
                return *radius;

            return defaultDisplayRadius;
        }

        constexpr Volume display_volume() const
        {
            return 4. / 3. * std::numbers::pi * math::cube(display_radius());
        }

