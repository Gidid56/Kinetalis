namespace chemistry { using atom::Atom; }

template <>
struct std::formatter<chemistry::Atom> : public std::formatter<chemistry::Element>
{
    template <class FormatContext>
    auto format(chemistry::Atom atom, FormatContext& context) const
    {
        switch (format_)
        {
            default:
            case Format::symbol:
                return std::format_to(
                    context.out(),
                    "{}{}{}",
                    symbol(atom.element),
                    abs(atom.charge) > 1 ? std::to_string(abs(atom.charge)) : "",
                    symbol(math::Sign{ math::sign(atom.charge) }));

            case Format::name:
                return std::format_to(
                    context.out(),
                    "{} (charge {})",
                    name(atom.element),
                    atom.charge);
        }
    }
};
